NS = 'http://www.sitemaps.org/schemas/sitemap/0.9'
IMG = 'http://www.google.com/schemas/sitemap-image/1.1'
ET.register_namespace('', NS)
ET.register_namespace('image', IMG)
root = ET.Element('{' + NS + '}urlset')
class Images(HTMLParser):
    def __init__(self):
        super().__init__(); self.paths = []
    def handle_starttag(self, tag, attrs):
        if tag == 'img':
            value = dict(attrs).get('src')
            if value:
                self.paths.append(value)
for path in pages():
    if path.name == 'resume.html':
        continue
    url = PRIMARY + route(path)
    item = ET.SubElement(root, '{' + NS + '}url')
    ET.SubElement(item, '{' + NS + '}loc').text = url
    ET.SubElement(item, '{' + NS + '}lastmod').text = DATE
    parser = Images(); parser.feed(path.read_text(encoding='utf-8'))
    seen = set()
    for image in parser.paths:
        image_url = urljoin(PRIMARY + '/' + path.relative_to(ROOT).as_posix(), image)
        if urlsplit(image_url).netloc != urlsplit(PRIMARY).netloc:
            continue
        # Encode spaces and other unsafe path characters without double encoding.
        from urllib.parse import quote, unquote
        image_url = PRIMARY + quote(unquote(urlsplit(image_url).path), safe='/')
        if image_url in seen:
            continue
        seen.add(image_url)
        node = ET.SubElement(item, '{' + IMG + '}image')
        ET.SubElement(node, '{' + IMG + '}loc').text = image_url
ET.indent(root, space='  ')
for name in ['sitemap.xml', 'sitemap-vercel.xml']:
    ET.ElementTree(root).write(ROOT / name, encoding='utf-8', xml_declaration=True)
write(ROOT / 'robots.txt', 'User-agent: *\nAllow: /\n\nSitemap: ' + PRIMARY + '/sitemap.xml\n')
print('Synced', len(root), 'canonical Vercel pages; static navigation and XML sitemaps updated.')
