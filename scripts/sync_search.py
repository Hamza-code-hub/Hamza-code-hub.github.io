def breadcrumbs(path, title):
    current = route(path)
    items = [('Home', PRIMARY + '/')]
    if current.startswith('/projects/'):
        items.append(('Portfolio', PRIMARY + '/portfolio.html'))
    elif current.startswith('/services/'):
        items.append(('Services', PRIMARY + '/services.html'))
    elif current.startswith('/research/') and current != '/research/':
        items.append(('Research', PRIMARY + '/research/'))
    items.append((title, PRIMARY + current))
    markup = '<nav class="site-breadcrumbs" aria-label="Breadcrumb"><ol>' + ''.join('<li>' + ('<span aria-current="page">' + escape(name) + '</span>' if index == len(items)-1 else '<a href="' + url + '">' + escape(name) + '</a>') + '</li>' for index, (name, url) in enumerate(items)) + '</ol></nav>'
    schema = {'@context': 'https://schema.org', '@type': 'BreadcrumbList', 'itemListElement': [{'@type': 'ListItem', 'position': i+1, 'name': name, 'item': url} for i, (name, url) in enumerate(items)]}
    return markup, '<script type="application/ld+json" data-site-breadcrumbs>\n' + json.dumps(schema, ensure_ascii=False, indent=2) + '\n</script>'

