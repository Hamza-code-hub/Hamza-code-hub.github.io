def pages():
    return sorted([*ROOT.glob('*.html'), *[p for folder in ['projects', 'resume', 'services', 'research'] for p in (ROOT / folder).glob('*.html')]])

def route(path):
    value = '/' + path.relative_to(ROOT).as_posix()
    return value[:-10] if value.endswith('index.html') else value

def text(markup):
    return unescape(re.sub('<[^>]+>', '', markup)).strip()

def write(path, value):
    with path.open('w', encoding='utf-8', newline='\n') as output:
        output.write(value)

def bing_verification(source, value):
    # Replace stale or duplicate tags, and remove verification when disabled.
    source = re.sub(r'''[ \t]*<meta\b(?=[^>]*\bname\s*=\s*(["'])msvalidate\.01\1)[^>]*>[ \t]*(?:\r?\n)?''', '', source, flags=re.I)
    if value:
        source = source.replace('</head>', '  <meta name="msvalidate.01" content="' + escape(value, quote=True) + '">\n</head>', 1)
    return source

